#!/usr/bin/env python3
"""Export glyph outlines of the system fonts we use to lib/glyphs.js, so the
lyric engine can build real extruded 3D letters (THREE.ExtrudeGeometry) with
the exact faces used in the 2D layer. Units: 1 em = 1.0, y up."""
import json, pathlib, sys
from fontTools.ttLib import TTCollection, TTFont
from fontTools.pens.basePen import BasePen

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")  # project dir
FONTS = {
    "FC": ("/System/Library/Fonts/Supplemental/Futura.ttc", "Futura-CondensedExtraBold"),
    "AVC": ("/System/Library/Fonts/Avenir Next Condensed.ttc", "AvenirNextCondensed-HeavyItalic"),
    "BODB": ("/System/Library/Fonts/Supplemental/Bodoni 72.ttc", "BodoniSvtyTwoITCTT-Bold"),
    "SCR": ("/System/Library/Fonts/Supplemental/SignPainter.ttc", "SignPainter-HouseScript"),
    "RND": ("/System/Library/Fonts/Supplemental/Arial Rounded Bold.ttf", "ArialRoundedMTBold"),
}
CHARS = "".join(chr(c) for c in range(32, 127)) + "’‘“”—–…✦"


class Rec(BasePen):
    def __init__(self, gs, upm):
        super().__init__(gs); self.c = []; self.k = 1 / upm
    def r(self, p): return [round(p[0] * self.k, 5), round(p[1] * self.k, 5)]
    def _moveTo(self, p): self.c.append(["m", *self.r(p)])
    def _lineTo(self, p): self.c.append(["l", *self.r(p)])
    def _curveToOne(self, a, b, p): self.c.append(["c", *self.r(a), *self.r(b), *self.r(p)])
    def _qCurveToOne(self, a, p): self.c.append(["q", *self.r(a), *self.r(p)])
    def _closePath(self): self.c.append(["z"])
    def _endPath(self): self.c.append(["z"])


def load(path, ps):
    fs = TTCollection(path).fonts if path.endswith(".ttc") else [TTFont(path)]
    for f in fs:
        if f["name"].getDebugName(6) == ps:
            return f
    raise SystemExit("missing " + ps)


out = {}
for key, (path, ps) in FONTS.items():
    f = load(path, ps)
    upm = f["head"].unitsPerEm
    cmap = f.getBestCmap()
    gs = f.getGlyphSet()
    hm = f["hmtx"]
    g = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if not name:
            continue
        pen = Rec(gs, upm)
        gs[name].draw(pen)
        g[ch] = {"a": round(hm[name][0] / upm, 5), "p": pen.c}
    os2 = f["OS/2"]
    out[key] = {"cff": "CFF " in f or "CFF2" in f, "asc": os2.sTypoAscender / upm, "desc": os2.sTypoDescender / upm,
                "cap": getattr(os2, "sCapHeight", 0) / upm or 0.7, "g": g}
    print(key, ps, "cff" if out[key]["cff"] else "ttf", len(g), "glyphs")
(ROOT / "lib/glyphs.js").write_text("// generated by fontjson.py\nwindow.GLYPHS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("bytes", (ROOT / "lib/glyphs.js").stat().st_size)
